"""Baselines vs the graph scorecard on the S1-S5 fixtures (ops_test). Writes docs/evaluation.md.

    set -a; . ./.env; set +a; FALKORDB_HOST=localhost uv run python -m eval.baseline

Rankers compared, all on the same injected scenario:
  coverage-only     top row of Q2: the node that explains the most alerting nodes (a naive
                    "common ancestor" answer, no probes, no paths, no changes)
  coverage + hops   the scorecard with only coverage and hop distance (graph topology, no evidence)
  full scorecard    rootgraph: coverage + probes + broken network paths + changes + memory
"""

from pathlib import Path

from agent import scoring
from agent.investigate import Investigator
from agent.sandbox import Scenario
from graph import db

NOW = 1792200000
EXPECTED = {"s1": {"sg-db"}, "s2": {"i-host2"}, "s3": {"svc:payments"}, "s4": {"sg-db"},
            "s5": {"sg-db", "svc:payments"}}
OUT = Path(__file__).resolve().parents[1] / "docs" / "evaluation.md"


def topology_only(rows):
    """Re-score the same candidates with coverage and hops only."""
    keep = {"coverage_ratio", "min_hops"}
    scored = [(sum(scoring.WEIGHTS[k] * v for k, v in r["components"].items() if k in keep), -r["components"]["min_hops"], r["rid"])
              for r in rows]
    return [rid for *_, rid in sorted(scored, key=lambda t: (-t[0], -t[1], t[2]))]


def run():
    g = db.graph("ops_test")
    results = []
    db.load_fixture(g)
    for name in ["s1", "s2", "s3", "s4", "s5"]:
        if name != "s4":
            db.load_fixture(g)
        else:  # S4 needs S1 resolved in memory first
            from agent import actions, memory
            from agent.tools import Tools
            db.load_fixture(g)
            sc1 = Scenario(g, "s1", NOW - 3600)
            inc1 = sc1.inject()["incident_id"]
            rep1 = Investigator(g, sc1.probes, now=lambda: NOW - 3600).run(inc1)
            act = rep1["proposals"][0]["action"]
            actions.approve(g, act["id"], "eval", NOW - 3590)
            actions.execute(g, act["id"], actions.SandboxExecutor(), NOW - 3580)
            sc1.recover(NOW - 3570)
            actions.verify(g, Tools(g), sc1.probes, act["id"], now=lambda: NOW - 3560, timeout=0)
            memory.close_incident(g, inc1, rep1["top"], act["id"], rep1["root_change_id"], rep1["explanation"], NOW - 3560)
        sc = Scenario(g, name, NOW)
        inc = sc.inject()["incident_id"]
        rep = Investigator(g, sc.probes, now=lambda: NOW).run(inc)
        corr = next(t for t in rep["trace"] if t["tool"] == "correlate_alerts")
        k = len(EXPECTED[name])
        results.append({
            "scenario": name, "title": sc.spec["title"], "expected": sorted(EXPECTED[name]),
            "coverage_only": [r["candidate"] for r in corr["rows"][:k]],
            "topology": topology_only(rep["scorecard"])[:k],
            "full": [r["rid"] for r in rep["scorecard"][:k]],
            "multiple": rep["multiple_causes"], "tool_calls": len(rep["trace"]),
        })
    g.delete()
    return results


def hit(pred, exp):
    return set(pred) == set(exp)


def markdown(results) -> str:
    lines = ["# Evaluation: does the graph evidence matter?", "",
             "Generated by `python -m eval.baseline` on the synthetic fixture scenarios (`graph/fixtures/scenarios/`).",
             "Each ranker sees the same injected incident. For S5 (two simultaneous faults) the top two must be the two causes.", "",
             "| Scenario | Expected | Coverage only | Coverage + hops | rootgraph scorecard |",
             "|---|---|---|---|---|"]
    tot = {"coverage_only": 0, "topology": 0, "full": 0}
    for r in results:
        cells = []
        for key in ("coverage_only", "topology", "full"):
            ok = hit(r[key], r["expected"])
            tot[key] += ok
            cells.append(("✓ " if ok else "✗ ") + ", ".join(f"`{x}`" for x in r[key]))
        lines.append(f"| {r['scenario'].upper()} {r['title']} | {', '.join(f'`{x}`' for x in r['expected'])} | " + " | ".join(cells) + " |")
    n = len(results)
    lines += [f"| **Correct** | | **{tot['coverage_only']}/{n}** | **{tot['topology']}/{n}** | **{tot['full']}/{n}** |", "",
              "What the columns mean:", "",
              "- **Coverage only** is the first row of Q2 (`correlate_alerts`): the node that explains the most alerting nodes.",
              "- **Coverage + hops** re-scores the same candidates with only the topology terms of the scorecard (no probes, paths, changes or memory).",
              "- **rootgraph scorecard** adds probe health, broken network paths (Q4/Q10), recent changes (Q5) and incident memory (Q7).", "",
              "Why coverage alone fails: in S1 and S4 the security-group rule is not on any dependency chain, so a pure upward walk "
              "can't reach it and blames host-1, which explains every alert but is healthy. In S5 it finds payments but misses `sg-db`. "
              "Only the path check (Q4 + Q10) surfaces `sg-db`, and only the probes clear host-1. Coverage is enough when the cause sits "
              "on the dependency chain itself (S2 shared host, S3 stopped service).", "",
              "Limits: five hand-made scenarios on a 17-node estate; the weights were tuned on them (see README, Limitations). "
              "This shows the mechanism, not general accuracy."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    res = run()
    OUT.write_text(markdown(res))
    print(OUT.read_text())
